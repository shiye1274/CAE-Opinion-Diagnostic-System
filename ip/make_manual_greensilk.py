class GManual(Manual):
    def fig(self, path, cap, width: float = 8.6) -> None:
        """插图默认宽度 8.6cm（压缩垂直占用，保证所在页正文仍 ≥30 行）。"""
        super().fig(path, cap, width)

    def _cover(self, doc) -> None:
        for _ in range(5):
            doc.add_paragraph()
        p = doc.add_paragraph()
        p.alignment = 1
        set_run(p.add_run(SOFT_NAME), 26, bold=True, cn_font=HEAD_CN_FONT)
        p = doc.add_paragraph()
        p.alignment = 1
        p.paragraph_format.space_before = Pt(10)
        set_run(p.add_run(f"版本号：{SOFT_VER}"), 14)
        for _ in range(3):
            doc.add_paragraph()
        p = doc.add_paragraph()
        p.alignment = 1
        set_run(p.add_run("使 用 说 明 书"), 30, bold=True, cn_font=HEAD_CN_FONT)
        for _ in range(6):
            doc.add_paragraph()
        for label, value in (("文档版本", SOFT_VER), ("编制日期", "2026 年 11 月")):
            p = doc.add_paragraph()
            p.alignment = 1
            p.paragraph_format.space_after = Pt(6)
            set_run(p.add_run(f"{label}：{value}"), 12)


