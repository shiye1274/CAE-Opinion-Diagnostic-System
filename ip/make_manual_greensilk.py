def load_facts() -> dict[str, Any]:
    db = sqlite3.connect(ROOT / "corpus" / "meta" / "corpus.sqlite")
    n, ar = db.execute(
        "SELECT COUNT(*), SUM(CASE WHEN language='ar' THEN 1 ELSE 0 END) "
        "FROM corpus_documents").fetchone()
    full = db.execute(
        "SELECT COUNT(*) FROM corpus_documents WHERE word_count >= 200").fetchone()[0]
    srcs = db.execute(
        "SELECT COUNT(DISTINCT source_id) FROM corpus_documents").fetchone()[0]
    ugc = db.execute("SELECT COUNT(*) FROM ugc_threads").fetchone()[0]
    words = db.execute("SELECT SUM(word_count) FROM corpus_documents").fetchone()[0]
    db.close()

    def _latest(pattern: str, folder: pathlib.Path) -> dict:
        files = sorted(folder.glob(pattern), key=lambda p: p.stat().st_mtime)
        if not files:
            return {}
        return json.loads(files[-1].read_text(encoding="utf-8"))

    align = {}
    p = ROOT / "models" / "evaluation" / "alignment_report.json"
    if p.exists():
        align = json.loads(p.read_text(encoding="utf-8"))
    silver = _latest("silver_report_*.json", ROOT / "annotation" / "data")

    return {
        "corpus": {"total": n, "arabic": ar, "ar_ratio": ar / max(n, 1),
                   "fulltext": full, "sources": srcs, "ugc": ugc, "words": words},
        "gates": {"fulltext": full >= 500, "sources": srcs >= 15,
                  "ar_ratio": ar / max(n, 1) >= 0.45},
        "align": align, "silver": silver,
    }


